#!/usr/bin/env python3
"""Render docs/MEMO.md from docs/MEMO_TEMPLATE.md + data/processed/metrics.json.

Prose lives in the template, numbers live in metrics.json, so a re-export cannot leave a
stale figure inside the argument. Fails on any unfilled {{token}}, and prepends an
unmissable banner when the numbers came from the fixture.

Usage:  python scripts/render_memo.py [--author "Your Name"]
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT))
sys.stdout.reconfigure(encoding="utf-8")
sys.stderr.reconfigure(encoding="utf-8")

from funnelscope import STAGE_LABELS, io as fio  # noqa: E402

TEMPLATE = REPO_ROOT / "docs" / "MEMO_TEMPLATE.md"
OUTPUT = REPO_ROOT / "docs" / "MEMO.md"

FIXTURE_BANNER = """> # ⚠ NOT AN ANALYSIS — SYNTHETIC FIXTURE OUTPUT
>
> Every number below was generated by `scripts/make_fixture.py` from a simulated event
> log. None of it describes Google's demo store or any real user behaviour. This file
> exists only to show that the pipeline renders end to end without GCP credentials.
>
> Replace it: `python scripts/run_queries.py && python scripts/analyze.py && python scripts/render_memo.py`

"""


def pct(x: float, places: int = 1) -> str:
    return f"{x * 100:.{places}f}%"


STEP_NAMES = {"added_to_cart": "add-to-cart", "began_checkout": "checkout-start",
              "purchased": "checkout-completion"}


def article(rendered: str) -> str:
    """"a" or "an" before a rendered number — "a 81.9% drop" reads as a typo.

    The article follows how the number is said: 8, 11 and 18 start with a vowel sound.
    """
    digits = rendered.lstrip("$").lstrip()
    return "an" if digits.startswith(("8", "11", "18")) else "a"


def money(x: float) -> str:
    return f"${x:,.0f}"


def build_tokens(m: dict, author: str) -> dict:
    f = m["funnel"]
    worst = f["worst_step"]
    opps = m["opportunities"]
    gap = m["segment_gap"] or {}

    funnel_rows = ["| Stage | Users | % of viewers | Step conversion |",
                   "|---|---:|---:|---:|"]
    stages = ["viewed", "added_to_cart", "began_checkout", "purchased"]
    for i, s in enumerate(stages):
        step = "—" if i == 0 else pct(f["step_conversion"][s])
        funnel_rows.append(
            f"| {STAGE_LABELS[s]} | {f[s]:,} | {pct(f[s] / f['viewed'])} | {step} |")

    dev_rows = ["| Segment | Viewed | Purchased | Conversion |", "|---|---:|---:|---:|"]
    for group in ("device", "visitor_type"):
        for r in m["segments"][group]:
            conv = r["purchased"] / r["viewed"] if r["viewed"] else 0
            dev_rows.append(f"| {r['segment_value']} | {r['viewed']:,} | "
                            f"{r['purchased']:,} | {pct(conv, 2)} |")

    intervals = {iv["to_stage"]: iv for iv in m.get("sizing_intervals", [])}
    opp_rows = ["| Step | Users lost | Recovered at +5pp | P(purchase \\| next stage) "
                "| Recoverable | 95% CI |",
                "|---|---:|---:|---:|---:|---:|"]
    for o in opps:
        iv = intervals.get(o["to_stage"])
        ci = f"{money(iv['ci_low'])} – {money(iv['ci_high'])}" if iv else "—"
        opp_rows.append(f"| {STAGE_LABELS[o['from_stage']]} → {STAGE_LABELS[o['to_stage']]} "
                        f"| {int(o['users_lost']):,} | {o['users_recovered']:,.0f} "
                        f"| {pct(o['downstream_conversion'], 1)} "
                        f"| {money(o['recoverable_revenue'])} | {ci} |")

    sens = m["sensitivity"]
    improvements = [k for k in sens[0] if k != "to_stage"]
    sens_rows = ["| Stage | " + " | ".join(f"+{float(i) * 100:.0f}pp" for i in improvements) + " |",
                 "|---" + "|---:" * len(improvements) + "|"]
    for r in sens:
        sens_rows.append("| " + STAGE_LABELS.get(r["to_stage"], r["to_stage"]) + " | " +
                         " | ".join(money(float(r[i])) for i in improvements) + " |")

    rice_rows = ["| # | Recommendation | Reach | Impact | Conf. | Effort (wk) | RICE |",
                 "|---|---|---:|---:|---:|---:|---:|"]
    for r in m["rice"]:
        rice_rows.append(f"| {int(r['rank'])} | {r['name']} | {int(r['reach']):,} | "
                         f"{r['impact']} | {r['confidence']} | {r['effort']} | "
                         f"{r['rice_score']:,.0f} |")
    top = m["rice"][0]
    # Only the top recommendation earns a paragraph; the rest are in the table.
    rice_reasoning = (
        f"**Why #1 ranks first:** {top['rationale']} *Assumption to challenge:* "
        f"{top['assumptions']}")

    # Only the two comparisons a reader would act on; the rest live in the dashboard.
    # Compact form, not stats.verdict(): the full sentence is written for a dashboard
    # tooltip and two of them would eat a third of the prose budget.
    sig = m["significance_tests"]
    def _short(t: dict) -> str:
        a, b = t["comparison"].split(" vs ")
        direction = "lower" if t["difference_pp"] < 0 else "higher"
        if not t["significant"]:
            return (f"**{a}** vs **{b}** ({pct(t['rate_a'], 2)} vs {pct(t['rate_b'], 2)}) "
                    f"is not distinguishable from noise at this sample size — "
                    f"p = {t['p_value']:.2f}. Do not act on it.")
        return (f"**{a}** converts {abs(t['difference_pp']):.2f}pp {direction} than "
                f"**{b}** ({pct(t['rate_a'], 2)} vs {pct(t['rate_b'], 2)}, 95% CI "
                f"[{t['ci_low_pp']:+.2f}, {t['ci_high_pp']:+.2f}]pp).")
    sig_para = " ".join(_short(t) for t in sig[:2]) if sig else ""
    if len(sig) > 2:
        n = len(sig) - 2
        sig_para += (f" ({n} further comparison{'s' if n != 1 else ''} "
                     f"{'are' if n != 1 else 'is'} in the dashboard.)")

    src = [s for s in m["segments"]["source"] if s["segment_value"] != "(long tail)"]
    for s in src:
        s["conv"] = s["purchased"] / s["viewed"] if s["viewed"] else 0
    big = sorted(src, key=lambda s: -s["viewed"])
    worst_ch = min(big[:5], key=lambda s: s["conv"]) if src else {}
    best_ch = max(src, key=lambda s: s["conv"]) if src else {}

    # Generated, so the memo cannot claim "the correction changes nothing" after a
    # re-export where it did.
    mc = m.get("multiple_comparisons") or {}
    if not mc:
        correction_sentence = ""
    elif mc.get("changed_by_correction"):
        correction_sentence = (
            f"**{len(mc['changed_by_correction'])} of these comparisons do not survive "
            f"{mc['method']} correction** across the family of {mc['family_size']} tests "
            f"({'; '.join(mc['changed_by_correction'])}) and are not treated as findings. "
            f"Running several segment comparisons at α = {mc['alpha']} each does not hold "
            f"the family-wise error rate at {mc['alpha']}.")
    else:
        correction_sentence = (
            f"{mc['n_significant_after_correction']} of {mc['family_size']} comparisons "
            f"survive {mc['method']} correction, and it flips none of them — the "
            f"survivors sit far below the adjusted thresholds. Worth stating rather than "
            f"using as a reason to skip the correction.")

    scope = m.get("scope_comparison")
    if scope:
        scope_sentence = (
            f"**{pct(scope['return_visit_dependence'], 0)} of conversions need a return "
            f"visit.** The same funnel scoped to the session converts at "
            f"{pct(scope['session_conversion'], 2)} against "
            f"{pct(scope['user_conversion'], 2)} user-level, so a single-session "
            f"optimisation would attack the wrong surface for that share of it.")
    else:
        scope_sentence = ""

    xv = m["validation"]["cross_validation"]
    max_rel = max(float(r["rel_diff"]) for r in xv)

    window_days = None
    try:
        import datetime as dt
        a = dt.date.fromisoformat(m["provenance"]["window_start"])
        b = dt.date.fromisoformat(m["provenance"]["window_end"])
        window_days = (b - a).days + 1  # inclusive: 1 Nov to 31 Jan is 92 days
    except Exception:
        pass

    # Sentences generated from what the data said, not fixed in the template. A template
    # that asserts a segment finding regardless of the z-test will eventually publish
    # something false.
    top_rec = m["rice"][0]
    if gap:
        gap_headline = (
            f"**{gap['segment_a']} converts {abs(gap['gap_pp']):.2f}pp below "
            f"{gap['segment_b']}** ({pct(gap['conversion_a'], 2)} vs "
            f"{pct(gap['conversion_b'], 2)}), the widest gap surviving Holm correction "
            f"(adjusted p = {gap.get('p_value_adjusted', float('nan')):.2g}). Closing it "
            f"was worth **{money(gap['value_if_closed'])}**, upper bound.")
        next_investigation = (
            f"**Why {gap['segment_a']} converts worse than {gap['segment_b']}.** Whether "
            f"it is friction or a difference in intent is not answerable from event "
            f"counts. Session recordings on that cohort would settle it.")
    else:
        rejected = ", ".join(
            f"{g.get('segment_type', 'segment')} {g['segment_a']} vs {g['segment_b']} "
            f"({abs(g['gap_pp']):.2f}pp, p = {g['p_value']:.2f})"
            for g in m.get("segment_gaps_all", []))
        gap_headline = (
            "**No segment gap survives correction.** Every cut tested — " +
            (rejected or "device, visitor type and channel") +
            " — is within sampling noise, so none of them is written up as a finding. "
            "The loss is whole-funnel, not concentrated in a segment.")
        next_investigation = (
            "**A cut this data does not contain.** No segment available here separates "
            "the drop-off, so the next question is which one would — logged-in status, "
            "product category, or price band, none of which survive obfuscation.")

    priority_bullet = (
        f"**Start with: {top_rec['name'].lower()}.** It leads RICE at "
        f"{top_rec['rice_score']:,.0f} against {m['rice'][1]['rice_score']:,.0f} next, "
        f"on a reach term ({int(top_rec['reach']):,} users) that is measured."
        if len(m["rice"]) > 1 else
        f"**Start with: {top_rec['name'].lower()}.** Its reach term "
        f"({int(top_rec['reach']):,} users) is measured rather than assumed.")

    tie_info = (m.get("validation") or {}).get("timestamp_ties")
    if tie_info and tie_info.get("excluded_by_tie"):
        tie_sentence = (
            f"**{tie_info['excluded_by_tie']:,} users ({pct(tie_info['share_of_counted'], 0)} "
            f"of the cart stage) are excluded by the strict ordering rule** — GA4 stamps "
            f"every event in one request with the same microsecond, so carting from a "
            f"listing ties with the view. Under `>=` the stage reads "
            f"{tie_info['counted_at_or_after']:,}. Strict is the conservative reading.")
    else:
        tie_sentence = ("**No funnel events share a timestamp**, so the strict ordering "
                        "rule excludes nobody.")

    exp = m.get("experiment") or {}
    plan_rows = ["| Step tested | Baseline | Smallest lift testable in 4 weeks | Users per arm | Runs for | Guardrails (must not fall) |",
                 "|---|---:|---:|---:|---:|---|"]
    for pl in exp.get("plans", []):
        lift = pl.get("smallest_detectable_lift")
        guards = "; ".join(g["metric"] for g in pl.get("guardrails", []))
        plan_rows.append(
            f"| {pl['primary_metric']} | {pct(pl['baseline'])} | "
            + (f"+{lift * 100:.0f} pts" if lift else "not testable") + " | "
            + (f"{pl['n_per_arm']:,}" if pl.get("n_per_arm") else "—") + " | "
            + (f"{pl['planned_days']} days" if pl.get("planned_days") else "—") + f" | {guards} |")

    testable = exp.get("practically_testable", [])
    top_step = next((pl for pl in exp.get("plans", []) if pl["step_to"] in testable), None)
    if top_step:
        test_sentence = (
            f"**Only the {STEP_NAMES.get(top_step['step_to'], top_step['step_to'])} fix is testable at "
            f"this traffic**: a {top_step['smallest_detectable_lift'] * 100:.0f}-point lift in "
            f"{top_step['planned_days'] // 7} weeks. Later steps see too few shoppers, so checkout "
            f"changes ship on judgement.")
    else:
        test_sentence = ("**No step can detect a lift under three points within four weeks at "
                         "this traffic**, so every change here would ship on judgement.")

    return {
        "test_plan_table": "\n".join(plan_rows),
        "test_plan_sentence": test_sentence,
        "author": author,
        "gap_headline": gap_headline,
        "priority_bullet": priority_bullet,
        "next_investigation": next_investigation,
        "tie_sentence": tie_sentence,
        "window_start": m["provenance"]["window_start"],
        "window_end": m["provenance"]["window_end"],
        "window_days": f"{window_days}" if window_days else "the analysis window's",
        "provenance_line": m["provenance"]["banner"],
        "viewed": f"{f['viewed']:,}",
        "end_to_end_conversion": pct(f["end_to_end_conversion"], 2),
        "worst_step_lost": f"{worst['lost']:,}",
        "worst_step_dropoff": pct(1 - worst["step_conversion"]),
        "worst_step_article": article(pct(1 - worst["step_conversion"])),
        "worst_step_label": f"{STAGE_LABELS[worst['from']]} → {STAGE_LABELS[worst['to']]}",
        "funnel_table": "\n".join(funnel_rows),
        "segment_table": "\n".join(dev_rows),
        "significance_paragraph": sig_para,
        "correction_sentence": correction_sentence,
        "scope_sentence": scope_sentence,
        "opportunity_table": "\n".join(opp_rows),
        "sensitivity_table": "\n".join(sens_rows),
        "rice_table": "\n".join(rice_rows),
        "rice_reasoning": rice_reasoning,
        "aov": f"${m['aov']:,.2f}",
        "sizing_equivalence": str(m.get("sizing_ranking_equals_step_conversion", "—")),
        "gap_segment_a": gap.get("segment_a", "the weaker segment"),
        "gap_segment_b": gap.get("segment_b", "the stronger segment"),
        "gap_pp": f"{abs(gap.get('gap_pp', 0)):.2f}pp",
        "gap_conv_a": pct(gap.get("conversion_a", 0), 2),
        "gap_conv_b": pct(gap.get("conversion_b", 0), 2),
        "gap_value": money(gap.get("value_if_closed", 0)),
        "gap_test_short": (f"p = {sig[0]['p_value']:.2g}" if sig else "see methodology"),
        "worst_channel": worst_ch.get("segment_value", "—"),
        "worst_channel_users": f"{worst_ch.get('viewed', 0):,}",
        "worst_channel_conv": pct(worst_ch.get("conv", 0), 2),
        "best_channel": best_ch.get("segment_value", "—"),
        "best_channel_users": f"{best_ch.get('viewed', 0):,}",
        "best_channel_conv": pct(best_ch.get("conv", 0), 2),
        "censored_share": pct(m["retention"]["censoring"]["share_censored"], 0),
        "xval_note": "first-occurrence timestamps vs. event-sequence regex",
        "xval_max_diff": f"{max_rel * 100:.2f}%",
    }


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--author", default="Ishaan Singh")
    args = ap.parse_args()

    metrics_path = fio.PROCESSED_DIR / "metrics.json"
    if not metrics_path.exists():
        print("No metrics.json. Run `python scripts/analyze.py` first.", file=sys.stderr)
        return 1
    m = json.loads(metrics_path.read_text(encoding="utf-8"))

    text = TEMPLATE.read_text(encoding="utf-8")
    tokens = build_tokens(m, args.author)
    for key, value in tokens.items():
        text = text.replace("{{" + key + "}}", str(value))

    leftover = set(re.findall(r"\{\{(\w+)\}\}", text))
    if leftover:
        print(f"Unfilled template tokens: {sorted(leftover)}", file=sys.stderr)
        return 1

    if not m["provenance"]["is_real"]:
        text = FIXTURE_BANNER + text

    OUTPUT.write_text(text, encoding="utf-8")

    # The 800-word budget is on the ARGUMENT. Tables are reference material a reader
    # scans; prose is what they have to read.
    # Excluded: table rows, the provenance banner, headings, rules, letterhead, footer.
    prose_lines = [ln for ln in text.splitlines()
                   if not ln.lstrip().startswith(
                       ("|", ">", "#", "---", "*Numbers",
                        "**To:**", "**From:**", "**Re:**", "**Data:**"))]
    words = len(re.sub(r"[`#*_]", " ", "\n".join(prose_lines)).split())
    print(f"Wrote {OUTPUT.relative_to(REPO_ROOT)}  ({words} words of prose, "
          f"tables excluded)")
    if words > 800:
        over = words - 800
        print(f"  WARNING: prose is {over} word{'s' if over != 1 else ''} over the "
              f"800-word budget. A memo nobody finishes is a memo that did not land.")
    if not m["provenance"]["is_real"]:
        print("Provenance: SYNTHETIC FIXTURE — warning banner prepended.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
