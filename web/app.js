  /* Volume on a log x-axis against conversion on y. Channel volumes span two orders of
   * magnitude; on a linear axis the small ones collapse onto the origin, which is
   * exactly where the scale opportunities live. */
  function scatterChart(rows) {
    var W = 720, H = 330, L = 52, Rp = 120, T = 16, B = 46;
    var svg = svgEl("svg", { viewBox: "0 0 " + W + " " + H, role: "img" });
    if (!rows.length) return svg;

    var vols = rows.map(function (r) { return Math.max(r.viewed, 1); });
    var minX = Math.min.apply(null, vols), maxX = Math.max.apply(null, vols);
    var lo = Math.log10(minX) - 0.12, hi = Math.log10(maxX) + 0.12;
    var maxY = Math.max.apply(null, rows.map(function (r) { return r.conversion; })) * 1.18 || 0.1;

    var x = function (v) { return L + ((Math.log10(Math.max(v, 1)) - lo) / (hi - lo)) * (W - L - Rp); };
    var y = function (v) { return T + (1 - v / maxY) * (H - T - B); };

    for (var g = 0; g <= 4; g++) {
      var v = (maxY * g) / 4;
      svg.appendChild(svgEl("line", { class: "grid-line", x1: L, x2: W - Rp, y1: y(v), y2: y(v) }));
      svg.appendChild(svgEl("text", { x: L - 8, y: y(v) + 4, "text-anchor": "end", text: pct(v, 1) }));
    }
    svg.appendChild(svgEl("line", { class: "axis", x1: L, x2: W - Rp, y1: y(0), y2: y(0) }));

    /* The site-average line turns a cloud of dots into a read. */
    var overall = D.funnel.overall[0].conversion;
    if (overall < maxY) {
      svg.appendChild(svgEl("line", {
        x1: L, x2: W - Rp, y1: y(overall), y2: y(overall),
        stroke: "var(--text-faint)", "stroke-width": 1.5, "stroke-dasharray": "5 4"
      }));

    }

    var rMax = Math.max.apply(null, rows.map(function (r) { return r.revenue_usd; })) || 1;
    var labels = [];
    rows.forEach(function (r, i) {
      var radius = 5 + 13 * Math.sqrt(Math.max(r.revenue_usd, 0) / rMax);
      var c = svgEl("circle", {
        cx: x(r.viewed), cy: y(r.conversion), r: radius,
        fill: color(i), opacity: 0.55, stroke: color(i), "stroke-width": 1.5
      });
      c.appendChild(svgEl("title", {
        text: r.channel + " — " + num(r.viewed) + " viewers, " +
          pct(r.conversion, 2) + " conversion, " + money(r.revenue_usd) + " revenue"
      }));
      svg.appendChild(c);
      labels.push({
        x: x(r.viewed) + radius + 5,
        y: y(r.conversion) + 4,
        text: r.channel.length > 22 ? r.channel.slice(0, 21) + "\u2026" : r.channel
      });
    });

    /* Nudge labels apart when bubbles cluster, or they overwrite each other right
     * where a reader is looking. */
    labels.sort(function (a, b) { return a.y - b.y; });
    for (var li = 1; li < labels.length; li++) {
      var minGap = 13;
      if (labels[li].y - labels[li - 1].y < minGap) {
        labels[li].y = labels[li - 1].y + minGap;
      }
    }
    labels.forEach(function (l) {
      svg.appendChild(svgEl("text", { x: l.x, y: l.y, text: l.text }));
    });

    [minX, Math.sqrt(minX * maxX), maxX].forEach(function (v) {
      svg.appendChild(svgEl("text", {
        x: x(v), y: H - B + 20, "text-anchor": "middle", text: num(v)
      }));
    });
    svg.appendChild(svgEl("text", {
      x: (L + W - Rp) / 2, y: H - 6, "text-anchor": "middle",
      text: "viewers (log scale) — bubble area is revenue"
    }));
    return svg;
  }

