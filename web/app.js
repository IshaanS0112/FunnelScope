  function renderOpportunity() {
    var intervals = {};
    (D.sizing_intervals || []).forEach(function (iv) { intervals[iv.to_stage] = iv; });

    mount("opportunity-table", table(D.opportunities, [
      {
        head: "Step", get: function (o) {
          return D.stage_labels[o.from_stage] + " → " + D.stage_labels[o.to_stage];
        }
      },
      { head: "Entering", num: true, get: function (o) { return num(o.users_entering); } },
      { head: "Lost", num: true, get: function (o) { return num(o.users_lost); } },
      { head: "Step conversion", num: true, get: function (o) { return pct(o.step_conversion); } },
      {
        head: "P(purchase | next stage)", num: true,
        get: function (o) { return pct(o.downstream_conversion); }
      },
      { head: "Recovered at +5pp", num: true, get: function (o) { return num(o.users_recovered); } },
      { head: "Recoverable", num: true, get: function (o) { return money(o.recoverable_revenue); } },
      {
        head: "95% CI", num: true, get: function (o) {
          var iv = intervals[o.to_stage];
          return iv ? money(iv.ci_low) + " – " + money(iv.ci_high) : "—";
        }
      }
    ]));

    var note = document.getElementById("equivalence-note");
    var equal = D.sizing_ranking_equals_step_conversion;
    note.innerHTML =
      "<strong>Sizing prices the stages. It does not re-rank them" +
      (equal === true ? "" : " (equivalence check: " + equal + ")") + ".</strong>" +
      "A frequent claim about opportunity sizing is that the biggest-revenue stage is " +
      "usually not the worst drop-off stage, and that the gap between them is the finding. " +
      "<strong>In a strictly ordered funnel that gap cannot exist.</strong> Every purchaser " +
      "passed through every stage, so <code>P(purchase | stage j) = purchases ÷ count_j</code>, " +
      "and recoverable revenue collapses to <code>1 / step_conversion</code> — strictly " +
      "monotone in the step rate. Ranking by dollars and ranking by worst drop-off are the " +
      "same ordering, necessarily, for every funnel. Treating them as two pieces of " +
      "evidence double-counts one fact. <strong>Effort</strong> is what re-ranks the work, " +
      "which is the RICE table's job. The property is asserted over random funnels in the " +
      "test suite, so a change to the model that breaks it fails loudly instead of quietly " +
      "manufacturing a finding." +
      "<br><br>The confidence intervals above price <em>sampling variation in the counts " +
      "only</em>. They do not price the improvement assumption, and they do not price the " +
      "model's load-bearing assumption that recovered users purchase like unaided " +
      "completers. A tight interval here means the counts are large, not that the number " +
      "is right.";

    /* Sensitivity sweep: rows are stages, columns are improvement assumptions. */
    var sens = D.sensitivity;
    if (sens && sens.length) {
      var keys = Object.keys(sens[0]).filter(function (k) { return k !== "to_stage"; });
      keys.sort(function (a, b) { return parseFloat(a) - parseFloat(b); });
      var cols = [{
        head: "Stage",
        get: function (r) { return D.stage_labels[r.to_stage] || r.to_stage; }
      }].concat(keys.map(function (k) {
        return {
          head: "+" + (parseFloat(k) * 100).toFixed(0) + "pp", num: true,
          get: function (r) { return money(r[k]); }
        };
      }));
      var ordered = D.opportunities.map(function (o) {
        return sens.filter(function (s) { return s.to_stage === o.to_stage; })[0];
      }).filter(Boolean);
      mount("sensitivity-table", table(ordered.length ? ordered : sens, cols));
    }

    renderSignificance();
    renderRice();
  }

