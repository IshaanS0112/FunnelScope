  /* ---------------- formatting ---------------- */

  var pct = function (x, places) {
    if (x === null || x === undefined || isNaN(x)) return "—";
    return (x * 100).toFixed(places === undefined ? 1 : places) + "%";
  };

  var num = function (x) {
    if (x === null || x === undefined || isNaN(x)) return "—";
    return Math.round(x).toLocaleString("en-US");
  };

  var money = function (x) {
    if (x === null || x === undefined || isNaN(x)) return "—";
    return "$" + Math.round(x).toLocaleString("en-US");
  };

  var pval = function (p) {
    if (p === null || p === undefined) return "—";
    if (p === 0) return "< 1e-300";
    return p < 0.001 ? p.toExponential(1) : p.toFixed(3);
  };

  var el = function (tag, attrs, children) {
    var node = document.createElement(tag);
    Object.keys(attrs || {}).forEach(function (k) {
      if (k === "class") node.className = attrs[k];
      else if (k === "html") node.innerHTML = attrs[k];
      else if (k === "text") node.textContent = attrs[k];
      else node.setAttribute(k, attrs[k]);
    });
    (children || []).forEach(function (c) { node.appendChild(c); });
    return node;
  };

  /* Build a table from a column spec: {head, get(row), num?, html?, cls(row)?}. */
  function table(rows, cols) {
    var thead = el("tr", {}, cols.map(function (c) {
      return el("th", { class: c.num ? "num" : "", text: c.head });
    }));
    var body = rows.map(function (r, i) {
      return el("tr", {}, cols.map(function (c) {
        var v = c.get(r, i);
        var attrs = { class: (c.num ? "num " : "") + (c.cls ? c.cls(r, i) : "") };
        if (c.html) attrs.html = v; else attrs.text = v;
        return el("td", attrs);
      }));
    });
    return el("table", {}, [el("thead", {}, [thead]), el("tbody", {}, body)]);
  }

  function mount(id, node) {
    var host = document.getElementById(id);
    if (!host) return;
    host.innerHTML = "";
    if (node) host.appendChild(node);
  }

  var SERIES = ["--series-1", "--series-2", "--series-3",
                "--series-4", "--series-5", "--series-6"];
  var color = function (i) { return "var(" + SERIES[i % SERIES.length] + ")"; };

  /* Minimal SVG helper — namespaced createElement. */
  var NS = "http://www.w3.org/2000/svg";
  function svgEl(tag, attrs) {
    var node = document.createElementNS(NS, tag);
    Object.keys(attrs || {}).forEach(function (k) {
      if (k === "text") node.textContent = attrs[k];
      else node.setAttribute(k, attrs[k]);
    });
    return node;
  }

